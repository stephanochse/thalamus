"""Write the human side of the weekly data: ROUTES.md, CHANGELOG.md and the generated blocks
inside README.md and AGENTS.md (between <!-- thalamus:NAME:start/end --> markers)."""
from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone

from .paths import DATA, REPO

ROLES = [("best", "Best"), ("value", "Value"), ("budget", "Budget"), ("fast", "Fast"), ("open", "Open weights")]
TIERS = [(90, "S"), (80, "A"), (70, "B"), (60, "C"), (50, "D"), (0, "F")]


def tier(score: float) -> str:
    return next(t for floor, t in TIERS if score >= floor)
GROUP_ORDER = ["Think", "Voice", "Build", "See", "Make", "Scale"]


def _money(r: dict | None) -> str:
    if not r or r.get("price") is None:
        return "n/a"
    p, unit = r["price"], r.get("price_unit", "usd_per_mtok")
    if unit == "usd_per_mtok":
        return f"${p:,.2f}/M" if p >= 0.1 else f"${p:,.3f}/M"
    return {"usd_per_image": f"${p:,.3f}/img", "usd_per_second": f"${p:,.3f}/s", "usd_per_minute": f"${p:,.3f}/min",
            "usd_per_mchar": f"${p:,.0f}/M chars"}.get(unit, f"${p:,.3f}")


def _short(r: dict | None) -> str:
    return f"{r['name']} ({_money(r)})" if r else "n/a"


def _grouped(jobs_meta: list[dict]) -> list[tuple[str, list[dict]]]:
    groups: dict[str, list[dict]] = {}
    for j in jobs_meta:
        groups.setdefault(j.get("group", "Other"), []).append(j)
    order = GROUP_ORDER + [g for g in groups if g not in GROUP_ORDER]
    return [(g, groups[g]) for g in order if g in groups]


def _dedupe(rows: list[dict], keep: int) -> list[dict]:
    """Show each base model once (its best-scoring variant) so tables aren't 4 effort levels of one model."""
    seen, out = set(), []
    for r in rows:
        base = r["id"].split("@", 1)[0]
        if base in seen:
            continue
        seen.add(base)
        out.append(r)
        if len(out) == keep:
            break
    return out


def routes_md(payload: dict, jobs_meta: list[dict]) -> str:
    jobs = payload["jobs"]
    lines = [f"# Model routes, week of {payload['updated']}", "",
             "Generated by the weekly sync from public leaderboards. Scores are 0-100 and relative to the other "
             "models scored for that job this week. Prices are per million tokens (blended 3:1 input:output) "
             "unless marked. See [docs/METHOD.md](docs/METHOD.md) for how scores are built.", ""]
    for group, members in _grouped(jobs_meta):
        lines += [f"## {group}", ""]
        for j in members:
            e = jobs.get(j["id"])
            if not e:
                continue
            lines += [f"### {e['title']}", ""]
            if e.get("about"):
                lines += [e["about"], ""]
            if not e["top"]:
                lines += ["_Not enough data this week._", ""]
                continue
            picks = e["picks"]
            lines.append(" | ".join(f"**{label}:** {_short(picks.get(k))}" for k, label in ROLES if picks.get(k)))
            if e.get("mix"):
                m = e["mix"]
                lines.append(f"\nMixed plan (best for 10% of tokens, value for 30%, budget for 60%): "
                             f"${m['mixed_per_mtok']}/M against ${m['all_best_per_mtok']}/M all-best, "
                             f"**{m['saves_pct']}% cheaper**.")
            lines += ["", "| # | Tier | Model | Lab | Score | Price | Speed | Based on |",
                      "|---|---|---|---|---|---|---|---|"]
            for r in _dedupe(e["top"], 10):
                basis = ", ".join(f"{k.split('.', 1)[-1]} {v}" for k, v in list(r["basis"].items())[:4])
                speed = f"{r['tps']:.0f} tok/s" if r.get("tps") else ""
                lines.append(f"| {r['rank']} | {tier(r['score'])} | {r['name']} | {r.get('lab') or ''} | {r['score']} | "
                             f"{_money(r)} | {speed} | {basis} |")
            lines += ["", f"_{e['ranked']} models ranked. Signals: {', '.join(e['metrics'])}._", ""]
    lines += ["## Sources this week", "", "| Source | Status | Rows | Fetched |", "|---|---|---|---|"]
    for key, s in payload["sources"].items():
        state = "ok" if s.get("ok") else ("stale (cached)" if s.get("stale") else "failed")
        lines.append(f"| [{s['name']}]({s['url']}) | {state} | {s.get('rows', 0)} | {s.get('fetched', '')} |")
    attributions = [s["attribution"] for s in payload["sources"].values() if s.get("attribution") and s.get("rows")]
    lines += ["", "Data credits: " + " ".join(attributions), ""]
    return "\n".join(lines)


def picks_table(payload: dict, jobs_meta: list[dict], with_ids: bool = False) -> str:
    jobs = payload["jobs"]
    head = "| Job | Best | Value | Budget | Mix saves |"
    lines = [head, "|---|---|---|---|---|"]
    for _, members in _grouped(jobs_meta):
        for j in members:
            e = jobs.get(j["id"])
            if not e or not e["picks"]:
                continue
            p = e["picks"]

            def cell(k: str) -> str:
                r = p.get(k)
                if not r:
                    return ""
                ident = f" `{r['openrouter']}`" if with_ids and r.get("openrouter") else ""
                return f"{r['name']}{ident}"
            saves = f"{e['mix']['saves_pct']}%" if e.get("mix") else ""
            lines.append(f"| {e['title']} | {cell('best')} | {cell('value')} | {cell('budget')} | {saves} |")
    return "\n".join(lines)


def _replace_block(path, name: str, body: str) -> bool:
    if not path.exists():
        return False
    text = path.read_text(encoding="utf-8")
    start, end = f"<!-- thalamus:{name}:start -->", f"<!-- thalamus:{name}:end -->"
    if start not in text or end not in text:
        return False
    new = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: f"{start}\n{body}\n{end}", text, flags=re.S)
    if new != text:
        path.write_text(new, encoding="utf-8")
    return True


def diff(previous: dict, payload: dict, catalog: list[dict], data_dir=None) -> dict:
    changes = {"pick_changes": [], "new_models": [], "headline": []}
    prev_jobs = (previous or {}).get("jobs", {})
    for job_id, e in payload["jobs"].items():
        old = prev_jobs.get(job_id, {}).get("picks", {})
        for role in ("best", "value", "budget"):
            new_pick, old_pick = e["picks"].get(role), old.get(role)
            if new_pick and old_pick and new_pick["id"] != old_pick["id"]:
                changes["pick_changes"].append(f"{e['title']}, {role}: {old_pick['name']} -> {new_pick['name']}")
    seen_path = (data_dir or DATA) / "seen.json"
    seen = set(json.loads(seen_path.read_text(encoding="utf-8"))) if seen_path.exists() else None
    cutoff = (datetime.now(timezone.utc) - timedelta(days=14)).strftime("%Y-%m-%d")
    scored = [m for m in catalog if not m.get("catalog_only")]
    for m in scored:
        is_new = (m["id"] not in seen) if seen is not None else ((m.get("released") or "") >= cutoff)
        if is_new and not m.get("variant"):
            changes["new_models"].append(f"{m['name']} ({m.get('lab') or 'unknown lab'})")
    seen_path.write_text(json.dumps(sorted({m["id"] for m in scored} | (seen or set())), indent=0), encoding="utf-8")
    changes["headline"] = (changes["pick_changes"][:6] +
                           ([f"{len(changes['new_models'])} newly scored models"] if changes["new_models"] else []))
    return changes


def changelog_entry(payload: dict, changes: dict) -> str:
    ok = [k for k, s in payload["sources"].items() if s.get("ok")]
    bad = [k for k, s in payload["sources"].items() if not s.get("ok")]
    lines = [f"## {payload['updated']}", "",
             f"Sources: {len(ok)} ok" + (f", not fresh: {', '.join(bad)}" if bad else "") + ".", ""]
    if changes["pick_changes"]:
        lines += ["Pick changes:", ""] + [f"- {c}" for c in changes["pick_changes"]] + [""]
    if changes["new_models"]:
        lines += [f"Newly scored ({len(changes['new_models'])}): " + ", ".join(changes["new_models"][:25])
                  + (" ..." if len(changes["new_models"]) > 25 else ""), ""]
    if not changes["pick_changes"] and not changes["new_models"]:
        lines += ["No pick changes this week.", ""]
    return "\n".join(lines)


def write_all(payload: dict, catalog: list[dict], changes: dict, jobs_meta: list[dict]) -> None:
    (REPO / "ROUTES.md").write_text(routes_md(payload, jobs_meta), encoding="utf-8")
    stamp = f"_Updated {payload['updated']} by the weekly sync. Full tables: [ROUTES.md](ROUTES.md)._"
    _replace_block(REPO / "README.md", "picks", picks_table(payload, jobs_meta) + "\n\n" + stamp)
    _replace_block(REPO / "AGENTS.md", "picks",
                   f"Current picks, week of {payload['updated']} (ids are OpenRouter slugs):\n\n"
                   + picks_table(payload, jobs_meta, with_ids=True))
    log = REPO / "CHANGELOG.md"
    entry = changelog_entry(payload, changes)
    old = log.read_text(encoding="utf-8") if log.exists() else "# Weekly changes\n\n"
    if f"## {payload['updated']}" in old:  # same-day re-run replaces that day's entry
        old = re.sub(rf"## {payload['updated']}\n.*?(?=\n## |\Z)", "", old, flags=re.S)
    head, _, rest = old.partition("\n\n")
    log.write_text(f"{head}\n\n{entry}\n{rest}".rstrip() + "\n", encoding="utf-8")
